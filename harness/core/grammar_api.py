"""The program language's machinery. PROTECTED. The node *definitions* live in harness/grammar/ (the loop extends
those); this file is how they are evaluated by the oracle and generated by the fuzzer.

A program is a JSON tree. A node is {"op": <name>, <arg>: <value>, ...}. An argument value is
  - another node (a dict with "op"), evaluated first,
  - a list, whose elements are evaluated one by one (so a list can mix nodes and literals),
  - or a typed literal (see encode.py): plain ints, {"bool": ..}, {"str": ..}, {"tuple": [..]}, ...

A node definition says what Python icepool does with the evaluated arguments, what kind of thing it returns (for
the generator: "die", "int", or any name a node introduces, e.g. "pool"), and how to generate a random instance.

Node status lives in harness/grammar/status.json: {"<op>": "ported" | "pending"}. The fuzzer only generates ported
nodes. A node may go pending -> ported, never back.
"""
import json
import os
import random
from dataclasses import dataclass, field
from typing import Callable, Optional

from harness.core.encode import dec

HERE = os.path.dirname(os.path.abspath(__file__))
STATUS_PATH = os.path.join(HERE, "..", "grammar", "status.json")


@dataclass
class Node:
    op: str
    returns: str
    run: Callable                       # python side: run(**evaluated_args) -> value
    gen: Optional[Callable] = None      # gen(g: Gen, depth: int) -> program dict; None = never generated
    leaf: bool = False                  # may be generated at depth 0
    weight: float = 1.0                 # relative generation frequency
    lazy: tuple = ()                    # argument names passed to run() unevaluated (raw JSON)
    doc: str = ""


NODES: dict[str, Node] = {}


def node(op, returns, gen=None, leaf=False, weight=1.0, lazy=(), doc=""):
    def deco(fn):
        if op in NODES:
            raise ValueError(f"node {op!r} defined twice")
        NODES[op] = Node(op, returns, fn, gen, leaf, weight, tuple(lazy), doc or (fn.__doc__ or "").strip())
        return fn
    return deco


def load_status():
    with open(STATUS_PATH) as f:
        return json.load(f)


def ported_ops():
    status = load_status()
    return {op for op, s in status.items() if s == "ported" and op in NODES}


def ops_in(program):
    """Every op used anywhere in a program."""
    found = set()

    def walk(x):
        if isinstance(x, dict):
            if "op" in x:
                found.add(x["op"])
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
    walk(program)
    return found


# --- Evaluation (oracle side) -----------------------------------------------------------------------------------

def evaluate(x):
    if isinstance(x, dict) and "op" in x:
        n = NODES.get(x["op"])
        if n is None:
            raise KeyError(f"unknown op {x['op']!r}")
        args = {k: (v if k in n.lazy else evaluate(v)) for k, v in x.items() if k != "op"}
        return n.run(**args)
    if isinstance(x, list):
        return [evaluate(v) for v in x]
    return dec(x)


# --- Generation (fuzzer side) -----------------------------------------------------------------------------------

@dataclass
class Gen:
    rng: random.Random
    allowed: set = field(default_factory=set)
    max_depth: int = 3

    def pick(self, returns, depth):
        cands = [n for n in NODES.values()
                 if n.op in self.allowed and n.returns == returns and n.gen is not None and (depth > 0 or n.leaf)]
        if not cands:
            return None
        return self.rng.choices(cands, weights=[n.weight for n in cands])[0]

    def make(self, returns, depth=None):
        """A random program returning `returns`. Built-in kind "int" falls back to a small literal."""
        if depth is None:
            depth = self.rng.randint(0, self.max_depth)
        n = self.pick(returns, depth)
        if n is None:
            if returns == "int":
                return self.rng.randint(-3, 6)
            n = self.pick(returns, 0)
            if n is None:
                raise LookupError(f"no ported generator returns {returns!r}")
        return n.gen(self, max(depth - 1, 0))

    def die(self, depth):
        return self.make("die", depth)

    def die_or_int(self, depth):
        return self.make("int", depth) if self.rng.random() < 0.3 else self.make("die", depth)

    def outcome(self):
        return self.rng.randint(-4, 12)


def kinds():
    return sorted({n.returns for n in NODES.values()})


def load_grammar():
    """Import every module in harness/grammar/ so their @node definitions register."""
    import importlib
    import pkgutil
    import harness.grammar as g
    for m in pkgutil.iter_modules(g.__path__):
        importlib.import_module(f"harness.grammar.{m.name}")
